import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
const require = createRequire(import.meta.url);
const { chromium } = require(process.argv[2] || 'playwright');
const output = resolve('output/playwright/reading-focus');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1200, height: 1000 } });
const page = await context.newPage();
const errors = [], checks = [];
page.on('pageerror', (error) => errors.push(error.message));
const check = (name) => checks.push(name);
const state = () => page.evaluate(() => ({ calls: window.readingFocusPreview.calls, ...window.readingFocusPreview.status }));
const phase = (value) => page.waitForFunction((value) => window.readingFocusPreview.status?.phase === value, value);
const ready = () => phase('ready');
const highlighted = () => phase('highlighted');
const enter = () => page.getByRole('button', { name: '开启辅助阅读', exact: true }).click();
const exit = () => page.getByRole('button', { name: '退出辅助阅读', exact: true }).click();
const calls = async () => (await state()).calls;
const opacity = (selector) => page.locator(selector).evaluate((node) => getComputedStyle(node).opacity);
const noDim = async () => {
  assert.equal(await opacity('#first'), '1');
  assert.equal(await opacity('#second'), '1');
  assert.equal(await page.evaluate(() => CSS.highlights.size), 0);
};
try {
  await page.goto('http://127.0.0.1:4193/');
  await page.waitForFunction(() => Boolean(window.readingFocusPreview));
  await page.evaluate(() => {
    window.readingFocusPreview.clearCache();
    localStorage.setItem('unrelated-preview-setting', 'preserve me');
  });
  const original = await page.locator('article').innerHTML();
  await page.evaluate(() => {
    window.originalClicks = 0;
    document.querySelector('#original-link').addEventListener('click', (event) => { event.preventDefault(); window.originalClicks++; });
  });
  await page.selectOption('#delay', '2000');
  await enter();
  await page.waitForFunction(() => window.readingFocusPreview.status.taskId);
  assert.equal((await state()).phase, 'preparing');
  await page.locator('#first').hover();
  await page.locator('#second').hover();
  await page.locator('#first').hover();
  await noDim();
  assert.equal(await calls(), 1);
  check('one whole-article task starts; pending hover neither dims nor creates tasks');

  const taskId = (await state()).taskId;
  await exit();
  await noDim();
  assert.equal(await page.locator('article').innerHTML(), original);
  await enter();
  await page.waitForFunction(() => window.readingFocusPreview.status.taskId);
  assert.equal((await state()).taskId, taskId);
  assert.equal(await calls(), 1);
  await ready();
  assert.equal(await calls(), 1);
  check('exit leaves the mock background task running; reentry subscribes to the same task');

  await page.locator('#first').hover();
  await highlighted();
  await page.waitForFunction(() => getComputedStyle(document.querySelector('#second')).opacity === '0.55');
  assert.equal(await opacity('#first'), '1');
  assert.equal(await opacity('nav'), '1');
  assert.equal(await opacity('#code'), '1');
  assert.equal(await opacity('#code-list'), '1');
  check('ready focus dims only readable article blocks; navigation and code stay unchanged');
  const ranges = await page.evaluate(() => [...CSS.highlights.values()].flatMap((highlight) => [...highlight].map((range) => range.toString())));
  assert(ranges.includes('Use a script'));
  assert.equal(await page.locator('#first strong').textContent(), 'script');
  check('native highlights cross inline nodes without rewriting the original English');

  await page.locator('#second').hover(); await highlighted();
  await page.locator('#third').hover(); await highlighted();
  await page.locator('#first').hover(); await highlighted();
  assert.equal(await calls(), 1);
  check('all ready paragraph switching is local and never submits additional analysis');
  await page.screenshot({ path: `${output}/focus.png`, fullPage: true, caret: 'initial' });
  await page.locator('#original-link').click();
  assert.equal(await page.evaluate(() => window.originalClicks), 1);
  check('original links and their event handlers remain active');

  await page.locator('#first').hover();
  await page.evaluate(() => {
    const node = document.querySelector('#first').lastChild;
    const start = node.textContent.indexOf('predictable');
    const range = document.createRange(); range.setStart(node, start); range.setEnd(node, start + 'predictable'.length);
    getSelection().removeAllRanges(); getSelection().addRange(range);
    document.querySelector('#first').dispatchEvent(new PointerEvent('pointerup', { bubbles: true, composed: true }));
  });
  const host = page.locator('[data-yebian-selection]');
  await host.getByRole('button', { name: '查词', exact: true }).click();
  await host.getByText('a. 可预测的', { exact: true }).waitFor();
  assert.equal(await page.evaluate(() => window.readingFocusPreview.saves), 0);
  await page.screenshot({ path: `${output}/dictionary.png`, caret: 'initial' });
  await host.getByRole('button', { name: '收藏单词' }).click();
  await host.getByRole('button', { name: '已收藏', exact: true }).waitFor();
  assert.equal(await page.evaluate(() => window.readingFocusPreview.saves), 1);
  assert.equal(await calls(), 1);
  check('mock dictionary shows a definition before explicit saving, without any analysis request');
  await page.keyboard.press('Escape');
  assert.equal(await page.evaluate(() => getSelection().isCollapsed), true);
  await page.locator('#second').hover();
  await page.waitForFunction(() => getComputedStyle(document.querySelector('#first')).opacity === '0.55');
  check('closing lookup releases its original selection and hover follows the next paragraph');

  await exit();
  assert.equal(await page.locator('article').innerHTML(), original);
  await noDim();
  check('exit restores exact article HTML, normal opacity, and removes all custom highlights');
  await enter(); await ready();
  assert.equal(await calls(), 1);
  await exit();
  await page.reload();
  await page.waitForFunction(() => Boolean(window.readingFocusPreview));
  await enter(); await ready();
  await page.locator('#first').hover(); await highlighted();
  assert.equal(await calls(), 0);
  check('ready whole-article cache survives exit and browser page reload with zero new tasks');

  await page.getByRole('button', { name: '清除预览缓存' }).click();
  assert.equal(await page.evaluate(() => localStorage.getItem('unrelated-preview-setting')), 'preserve me');
  await page.getByRole('button', { name: '模拟失败' }).click();
  await enter(); await phase('error');
  assert.equal((await state()).taskStatus, 'failed');
  await noDim();
  const failedCalls = await calls();
  await exit(); await enter(); await phase('error');
  assert.equal(await calls(), failedCalls);
  check('simulated failure is explicit, leaves ordinary reading, and reentry does not silently retry');
  await page.getByRole('button', { name: '模拟失败' }).click();
  await page.getByRole('button', { name: '重试分析', exact: true }).click();
  await ready();
  assert.equal(await calls(), failedCalls + 1);
  check('explicit retry creates exactly one replacement task and can recover');

  await page.getByRole('button', { name: '清除预览缓存' }).click();
  await page.selectOption('#delay', '6000');
  await enter();
  await page.waitForFunction(() => window.readingFocusPreview.status.taskId);
  const stoppedCalls = await calls();
  await page.getByRole('button', { name: '停止分析', exact: true }).click();
  await phase('error');
  assert.equal((await state()).taskStatus, 'stopped');
  await exit(); await enter(); await phase('error');
  assert.equal((await state()).taskStatus, 'stopped');
  assert.equal(await calls(), stoppedCalls);
  await noDim();
  check('stop cancels the mock timer and reentry preserves stopped state without resubmission');

  await page.getByRole('button', { name: '清除预览缓存' }).click();
  await page.setViewportSize({ width: 360, height: 760 });
  await page.emulateMedia({ reducedMotion: 'reduce', colorScheme: 'dark' });
  await page.selectOption('#delay', '250');
  await enter(); await ready();
  await page.locator('#first').hover(); await highlighted();
  assert.equal(await page.locator('#first').evaluate((node) => getComputedStyle(node).transitionDuration), '0s');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: `${output}/narrow-reduced-motion.png`, fullPage: true, caret: 'initial' });
  await exit();
  assert.equal(await page.locator('article').innerHTML(), original);
  check('narrow viewport and reduced-motion reading remain usable and exit still restores HTML');
  assert.deepEqual(errors, []);
  await writeFile(`${output}/checks.json`, JSON.stringify({ mockOnly: true, checks, errors }, null, 2));
  console.log(JSON.stringify({ mockOnly: true, passed: checks.length, checks, errors, output }, null, 2));
} finally { await context.close(); await browser.close(); }
